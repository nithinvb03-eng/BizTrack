package com.sathya.co.biztrack.service;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.sathya.co.biztrack.dto.CreditReceiptResponse;
import java.io.ByteArrayOutputStream;
import java.text.NumberFormat;
import java.time.format.DateTimeFormatter;
import java.util.Locale;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

@Service
public class CreditReceiptPdfService {

    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("dd MMM yyyy", Locale.ENGLISH);
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("hh:mm a", Locale.ENGLISH);
    private static final DateTimeFormatter DATE_TIME =
            DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a", Locale.ENGLISH);

    public byte[] create(CreditReceiptResponse receipt) {
        try (ByteArrayOutputStream output = new ByteArrayOutputStream()) {
            Document document = new Document();
            PdfWriter.getInstance(document, output);
            document.open();

            Font title = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18);
            Font bold = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10);
            Font normal = FontFactory.getFont(FontFactory.HELVETICA, 10);

            document.add(new Paragraph(receipt.businessName(), title));
            if (receipt.businessGstin() != null && !receipt.businessGstin().isBlank()) {
                document.add(new Paragraph("GSTIN: " + receipt.businessGstin(), normal));
            }
            document.add(new Paragraph("CREDIT GIVEN RECEIPT", bold));
            document.add(new Paragraph("Receipt number: " + receipt.receiptNo(), normal));
            document.add(new Paragraph("Generated: " + DATE_TIME.format(receipt.generatedAt()), normal));
            document.add(new Paragraph("Generated by: " + receipt.generatedBy(), normal));
            document.add(new Paragraph("Credit taker: " + receipt.creditTakerName(), normal));
            document.add(new Paragraph("Type: " + receipt.type(), normal));
            if (receipt.phone() != null) {
                document.add(new Paragraph("Phone: " + receipt.phone(), normal));
            }
            document.add(new Paragraph(
                    "Period: " + DATE.format(receipt.periodFrom()) + " to " + DATE.format(receipt.periodTo()),
                    normal));
            document.add(new Paragraph(" "));

            PdfPTable table = new PdfPTable(new float[] {1.5f, 1.2f, 1.3f, 3.2f});
            table.setWidthPercentage(100);
            addCell(table, "Date", bold);
            addCell(table, "Time", bold);
            addCell(table, "Amount", bold);
            addCell(table, "Note", bold);
            for (CreditReceiptResponse.ReceiptEntry entry : receipt.entries()) {
                addCell(table, DATE.format(entry.date()), normal);
                addCell(table, TIME.format(entry.time()), normal);
                addCell(table, "Rs. " + indianAmount(entry.amount()), normal);
                addCell(table, entry.note() == null ? "" : entry.note(), normal);
            }
            document.add(table);
            document.add(new Paragraph(" "));
            document.add(new Paragraph("Number of entries: " + receipt.entryCount(), bold));
            document.add(new Paragraph("TOTAL CREDIT GIVEN: Rs. " + indianAmount(receipt.totalAmount()), bold));
            document.close();
            return output.toByteArray();
        } catch (DocumentException | java.io.IOException exception) {
            throw new ResponseStatusException(
                    HttpStatus.INTERNAL_SERVER_ERROR, "The receipt PDF could not be created.", exception);
        }
    }

    private void addCell(PdfPTable table, String text, Font font) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setPadding(6);
        table.addCell(cell);
    }

    private String indianAmount(java.math.BigDecimal amount) {
        NumberFormat format = NumberFormat.getNumberInstance(Locale.forLanguageTag("en-IN"));
        format.setMinimumFractionDigits(2);
        format.setMaximumFractionDigits(2);
        return format.format(amount);
    }
}
